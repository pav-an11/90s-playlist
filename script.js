let playlist = [];
let currentIndex = 0;
let isPlaying = false;
let audio = new Audio();

// 1. We added the songTitleEl here
const playBtn = document.getElementById("play-btn");
const prevBtn = document.getElementById("prev-btn");
const nextBtn = document.getElementById("next-btn");
const progressBar = document.getElementById("progress-bar");
const currentTimeEl = document.getElementById("current-time");
const totalTimeEl = document.getElementById("total-time");
const visualizer = document.getElementById("visualizer");
const songTitleEl = document.getElementById("song-title"); 

function shuffleArray(array) {
    let shuffled = [...array];
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
    }
    return shuffled;
}

function initPlayer() {
    playlist = shuffleArray(songs);
    loadSong(currentIndex);
}

// 2. We replaced the old loadSong function with this new one
function loadSong(index) {
    let currentPath = playlist[index].url;
    audio.src = currentPath;
    
    // Clean up the messy file name to show only the song title
    let cleanName = currentPath;
    cleanName = cleanName.replace("music/", "");         // Removes folder name
    cleanName = cleanName.replace(".mp3", "");           // Removes extension
    cleanName = cleanName.replace("_spotdown.org", "");  // Removes the website tag
    cleanName = cleanName.replace(/_/g, " ");            // Replaces underscores with spaces
    
    // Update the HTML text
    songTitleEl.textContent = cleanName;
}

function togglePlay() {
    if (isPlaying) {
        audio.pause();
        playBtn.textContent = "▶";
        playBtn.classList.remove("playing");
        visualizer.classList.remove("active");
    } else {
        audio.play();
        playBtn.textContent = "⏸";
        playBtn.classList.add("playing");
        visualizer.classList.add("active");
    }
    isPlaying = !isPlaying;
}

function playNext() {
    currentIndex = (currentIndex + 1) % playlist.length;
    loadSong(currentIndex);
    if (isPlaying) audio.play();
}

function playPrev() {
    currentIndex = (currentIndex - 1 + playlist.length) % playlist.length;
    loadSong(currentIndex);
    if (isPlaying) audio.play();
}

function formatTime(seconds) {
    if (isNaN(seconds)) return "0:00";
    const minutes = Math.floor(seconds / 60);
    const secs = Math.floor(seconds % 60);
    return `${minutes}:${secs < 10 ? '0' : ''}${secs}`;
}

function updateProgress(e) {
    const { duration, currentTime } = e.srcElement;
    if (!isNaN(duration)) {
        const progressPercent = (currentTime / duration) * 100;
        progressBar.value = progressPercent;
        currentTimeEl.textContent = formatTime(currentTime);
        totalTimeEl.textContent = formatTime(duration);
    }
}

function setProgress(e) {
    const width = this.clientWidth;
    const clickX = e.offsetX;
    const duration = audio.duration;
    audio.currentTime = (clickX / width) * duration;
}

// Event Listeners
playBtn.addEventListener("click", togglePlay);
nextBtn.addEventListener("click", playNext);
prevBtn.addEventListener("click", playPrev);
audio.addEventListener('timeupdate', updateProgress);
progressBar.addEventListener('click', setProgress);

audio.addEventListener('loadedmetadata', () => {
    totalTimeEl.textContent = formatTime(audio.duration);
});

audio.addEventListener("ended", playNext);

// Start
initPlayer();